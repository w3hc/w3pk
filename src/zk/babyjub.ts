/**
 * Baby Jubjub (EIP-2494) point arithmetic and keys
 * Matches circomlib's babyjub gadgets and circomlibjs's encodings
 */

import { hkdf } from "@noble/hashes/hkdf.js";
import { sha256 } from "@noble/hashes/sha2.js";
import { CryptoError } from "../core/errors";
import { bufferToBigInt } from "./utils";

/** Affine point `[x, y]`, the layout circom signals use */
export type BabyJubPoint = readonly [bigint, bigint];

export interface BabyJubKeyPair {
  /** Scalar in `[1, BABYJUB_SUBORDER)` */
  privateKey: bigint;
  /** `privateKey · BABYJUB_BASE8` */
  publicKey: BabyJubPoint;
}

/** Base field: the BN254 scalar field */
export const BABYJUB_FIELD =
  21888242871839275222246405745257275088548364400416034343698204186575808495617n;
export const BABYJUB_A = 168700n;
export const BABYJUB_D = 168696n;
/** Curve order, `8 · BABYJUB_SUBORDER` */
export const BABYJUB_ORDER =
  21888242871839275222246405745257275088614511777268538073601725287587578984328n;
/** Prime order `l` of the subgroup generated by `BABYJUB_BASE8` */
export const BABYJUB_SUBORDER = BABYJUB_ORDER >> 3n;
export const BABYJUB_GENERATOR: BabyJubPoint = [
  995203441582195749578291179787384436505546430278305826713579947235728471134n,
  5472060717959818805561601436314318772137091100104008585924551046643952123905n,
];
/** `8 · BABYJUB_GENERATOR`, the base point of circomlib's `BabyPbk` and `EscalarMulFix` */
export const BABYJUB_BASE8: BabyJubPoint = [
  5299619240641551281634865583518297030282874472190772894086521144482721001553n,
  16950150798460657717958625567821834550301663161624707787222815936182638968203n,
];
export const BABYJUB_IDENTITY: BabyJubPoint = [0n, 1n];

const P = BABYJUB_FIELD;
const HALF_P = (P - 1n) >> 1n;
const KEY_INFO = new TextEncoder().encode("w3pk-babyjub-v1");

const SCALAR_BITS = 256;
const MAX_DISCRETE_LOG = 2 ** 32;

type Projective = [bigint, bigint, bigint];

function mod(a: bigint): bigint {
  const r = a % P;
  return r < 0n ? r + P : r;
}

function inv(a: bigint): bigint {
  let [r0, r1] = [mod(a), P];
  let [s0, s1] = [1n, 0n];
  if (r0 === 0n) throw new CryptoError("Division by zero in Baby Jubjub field");
  while (r1 !== 0n) {
    const q = r0 / r1;
    [r0, r1] = [r1, r0 - q * r1];
    [s0, s1] = [s1, s0 - q * s1];
  }
  return mod(s0);
}

function pow(base: bigint, exp: bigint): bigint {
  let result = 1n;
  let b = mod(base);
  let e = exp;
  while (e > 0n) {
    if (e & 1n) result = (result * b) % P;
    b = (b * b) % P;
    e >>= 1n;
  }
  return result;
}

const TWO_ADICITY = 28n;
const ODD_PART = (P - 1n) >> TWO_ADICITY;
const NON_RESIDUE = 5n;

function sqrt(a: bigint): bigint | null {
  const n = mod(a);
  if (n === 0n) return 0n;
  if (pow(n, HALF_P) !== 1n) return null;
  let m = TWO_ADICITY;
  let c = pow(NON_RESIDUE, ODD_PART);
  let t = pow(n, ODD_PART);
  let r = pow(n, (ODD_PART + 1n) >> 1n);
  while (t !== 1n) {
    let i = 0n;
    let t2 = t;
    while (t2 !== 1n) {
      t2 = (t2 * t2) % P;
      i++;
    }
    const b = pow(c, 1n << (m - i - 1n));
    m = i;
    c = (b * b) % P;
    t = (t * c) % P;
    r = (r * b) % P;
  }
  return r;
}

function addProjective(p: Projective, q: Projective): Projective {
  const [x1, y1, z1] = p;
  const [x2, y2, z2] = q;
  const a = (z1 * z2) % P;
  const b = (a * a) % P;
  const c = (x1 * x2) % P;
  const d = (y1 * y2) % P;
  const e = (((BABYJUB_D * c) % P) * d) % P;
  const f = mod(b - e);
  const g = (b + e) % P;
  const x3 = mod(a * f * ((x1 + y1) * (x2 + y2) - c - d));
  const y3 = mod(a * g * (d - BABYJUB_A * c));
  const z3 = (f * g) % P;
  return [x3, y3, z3];
}

function toAffine([x, y, z]: Projective): BabyJubPoint {
  const zi = inv(z);
  return [(x * zi) % P, (y * zi) % P];
}

function addUnchecked(p: BabyJubPoint, q: BabyJubPoint): BabyJubPoint {
  return toAffine(addProjective([p[0], p[1], 1n], [q[0], q[1], 1n]));
}

function mulUnchecked(p: BabyJubPoint, e: bigint): BabyJubPoint {
  let r0: Projective = [0n, 1n, 1n];
  let r1: Projective = [p[0], p[1], 1n];
  const bits = Math.max(SCALAR_BITS, e.toString(2).length);
  for (let i = bits - 1; i >= 0; i--) {
    const bit = (e >> BigInt(i)) & 1n;
    const sum = addProjective(r0, r1);
    const doubled = bit ? addProjective(r1, r1) : addProjective(r0, r0);
    r0 = bit ? sum : doubled;
    r1 = bit ? doubled : sum;
  }
  return toAffine(r0);
}

function assertScalar(e: bigint, name: string): void {
  if (typeof e !== "bigint" || e < 0n) {
    throw new CryptoError(`${name} must be a non-negative bigint`);
  }
}

function assertPoint(p: BabyJubPoint, name: string): void {
  if (!isOnBabyJub(p)) {
    throw new CryptoError(`${name} is not a point on Baby Jubjub`);
  }
}

/**
 * Check that `p` has canonical coordinates in `[0, p)` and lies on the curve
 */
export function isOnBabyJub(p: BabyJubPoint): boolean {
  if (!Array.isArray(p) || p.length !== 2) return false;
  const [x, y] = p;
  if (typeof x !== "bigint" || typeof y !== "bigint") return false;
  if (x < 0n || x >= P || y < 0n || y >= P) return false;
  const x2 = (x * x) % P;
  const y2 = (y * y) % P;
  return mod(BABYJUB_A * x2 + y2) === mod(1n + ((BABYJUB_D * x2) % P) * y2);
}

/**
 * Check that `p` lies on the curve and in the prime-order subgroup,
 * which rejects the small-order (torsion) points
 */
export function isInBabyJubSubgroup(p: BabyJubPoint): boolean {
  if (!isOnBabyJub(p)) return false;
  const [x, y] = mulUnchecked(p, BABYJUB_SUBORDER);
  return x === 0n && y === 1n;
}

export function babyJubAdd(p: BabyJubPoint, q: BabyJubPoint): BabyJubPoint {
  assertPoint(p, "First point");
  assertPoint(q, "Second point");
  return addUnchecked(p, q);
}

export function babyJubNeg(p: BabyJubPoint): BabyJubPoint {
  assertPoint(p, "Point");
  return [mod(-p[0]), p[1]];
}

/**
 * Scalar multiplication `e · p` by a Montgomery ladder over at least 256
 * bits, so the work doesn't depend on the scalar's bits. The scalar is
 * not reduced, so `babyJubMul(p, BABYJUB_SUBORDER)` exposes torsion components
 */
export function babyJubMul(p: BabyJubPoint, e: bigint): BabyJubPoint {
  assertPoint(p, "Point");
  assertScalar(e, "Scalar");
  return mulUnchecked(p, e);
}

export function babyJubEquals(p: BabyJubPoint, q: BabyJubPoint): boolean {
  return p[0] === q[0] && p[1] === q[1];
}

/**
 * Pack a point into 32 bytes as circomlibjs's `packPoint` does:
 * `y` little-endian, with the top bit set when `x > (p - 1) / 2`
 */
export function packBabyJubPoint(p: BabyJubPoint): Uint8Array {
  assertPoint(p, "Point");
  const out = new Uint8Array(32);
  let y = p[1];
  for (let i = 0; i < 32; i++) {
    out[i] = Number(y & 0xffn);
    y >>= 8n;
  }
  if (p[0] > HALF_P) out[31] |= 0x80;
  return out;
}

/**
 * Unpack 32 bytes from `packBabyJubPoint`. Rejects non-canonical `y`,
 * encodings with no point on the curve, and a sign bit on `x = 0`.
 * Does not check the subgroup: use `unpackBabyJubPublicKey` for keys
 */
export function unpackBabyJubPoint(bytes: Uint8Array): BabyJubPoint {
  if (!(bytes instanceof Uint8Array) || bytes.length !== 32) {
    throw new CryptoError("Packed Baby Jubjub point must be 32 bytes");
  }
  const sign = (bytes[31] & 0x80) !== 0;
  let y = 0n;
  for (let i = 31; i >= 0; i--) {
    y = (y << 8n) | BigInt(i === 31 ? bytes[i] & 0x7f : bytes[i]);
  }
  if (y >= P) throw new CryptoError("Packed Baby Jubjub point is not canonical");
  const y2 = (y * y) % P;
  const x2 = mod((1n - y2) * inv(BABYJUB_A - BABYJUB_D * y2));
  let x = sqrt(x2);
  if (x === null) throw new CryptoError("Packed bytes are not a Baby Jubjub point");
  if (x === 0n && sign) throw new CryptoError("Packed Baby Jubjub point is not canonical");
  if (x > HALF_P !== sign) x = P - x;
  return [x, y];
}

/**
 * A public key must be in the prime-order subgroup and not the identity
 */
export function isValidBabyJubPublicKey(p: BabyJubPoint): boolean {
  return isInBabyJubSubgroup(p) && !babyJubEquals(p, BABYJUB_IDENTITY);
}

export function assertBabyJubPublicKey(p: BabyJubPoint): void {
  if (!isValidBabyJubPublicKey(p)) {
    throw new CryptoError(
      "Invalid Baby Jubjub public key: not in the prime-order subgroup or the identity"
    );
  }
}

export function assertBabyJubPrivateKey(privateKey: bigint): void {
  if (
    typeof privateKey !== "bigint" ||
    privateKey < 1n ||
    privateKey >= BABYJUB_SUBORDER
  ) {
    throw new CryptoError("Baby Jubjub private key must be in [1, l)");
  }
}

export function packBabyJubPublicKey(publicKey: BabyJubPoint): Uint8Array {
  assertBabyJubPublicKey(publicKey);
  return packBabyJubPoint(publicKey);
}

export function unpackBabyJubPublicKey(bytes: Uint8Array): BabyJubPoint {
  const p = unpackBabyJubPoint(bytes);
  assertBabyJubPublicKey(p);
  return p;
}

function bytesToScalar(bytes: Uint8Array): bigint {
  return (bufferToBigInt(bytes) % (BABYJUB_SUBORDER - 1n)) + 1n;
}

/**
 * Uniform scalar in `[1, BABYJUB_SUBORDER)`, from 64 random bytes
 */
export function randomBabyJubScalar(): bigint {
  const bytes = new Uint8Array(64);
  crypto.getRandomValues(bytes);
  return bytesToScalar(bytes);
}

/**
 * Public key `privateKey · BABYJUB_BASE8`, as circomlib's `BabyPbk` computes it
 */
export function babyJubPublicKey(privateKey: bigint): BabyJubPoint {
  assertBabyJubPrivateKey(privateKey);
  return mulUnchecked(BABYJUB_BASE8, privateKey);
}

export function generateBabyJubKeyPair(): BabyJubKeyPair {
  const privateKey = randomBabyJubScalar();
  return { privateKey, publicKey: babyJubPublicKey(privateKey) };
}

/**
 * Derive a key pair from a secret of at least 16 bytes, such as
 * `derivePrfSecret()`'s output. The scalar is
 * `HKDF-SHA256(secret, info = "w3pk-babyjub-v1", 64 bytes) mod (l - 1) + 1`
 */
export function deriveBabyJubKeyPair(secret: Uint8Array): BabyJubKeyPair {
  if (!(secret instanceof Uint8Array) || secret.length < 16) {
    throw new CryptoError("Baby Jubjub key secret must be at least 16 bytes");
  }
  const privateKey = bytesToScalar(hkdf(sha256, secret, undefined, KEY_INFO, 64));
  return { privateKey, publicKey: babyJubPublicKey(privateKey) };
}

/**
 * Smallest `m` in `[0, maxValue]` with `m · BABYJUB_BASE8 = point`, by
 * baby-step giant-step, or `null` when there is none. `maxValue` is at
 * most 2^32, which takes about 2^17 point additions
 */
export function babyJubDiscreteLog(
  point: BabyJubPoint,
  maxValue: number
): bigint | null {
  assertPoint(point, "Point");
  if (!Number.isInteger(maxValue) || maxValue < 0 || maxValue > MAX_DISCRETE_LOG) {
    throw new CryptoError("maxValue must be an integer in [0, 2^32]");
  }
  const steps = Math.ceil(Math.sqrt(maxValue + 1));
  const table = new Map<string, number>();
  let baby: BabyJubPoint = BABYJUB_IDENTITY;
  for (let j = 0; j < steps; j++) {
    const key = `${baby[0]},${baby[1]}`;
    if (!table.has(key)) table.set(key, j);
    baby = addUnchecked(baby, BABYJUB_BASE8);
  }
  const giant = babyJubNeg(mulUnchecked(BABYJUB_BASE8, BigInt(steps)));
  let gamma = point;
  for (let i = 0; i < steps; i++) {
    const j = table.get(`${gamma[0]},${gamma[1]}`);
    if (j !== undefined) {
      const m = i * steps + j;
      return m <= maxValue ? BigInt(m) : null;
    }
    gamma = addUnchecked(gamma, giant);
  }
  return null;
}
