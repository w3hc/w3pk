#!/usr/bin/env node
/**
 * Inlines a bundle of @noble/hashes argon2idAsync into
 * standalone/extract-mnemonic.html, between the argon2id:start and
 * argon2id:end markers, so the page decrypts BackupFile v3 offline.
 *
 * Run after upgrading @noble/hashes: pnpm build:standalone
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const page = join(root, 'standalone', 'extract-mnemonic.html');
const { version } = JSON.parse(
  readFileSync(join(root, 'node_modules', '@noble', 'hashes', 'package.json'), 'utf8')
);

const result = await build({
  stdin: {
    contents: "export { argon2idAsync } from '@noble/hashes/argon2.js';",
    resolveDir: root,
    loader: 'js',
  },
  bundle: true,
  format: 'iife',
  globalName: 'nobleArgon2',
  minify: true,
  target: 'es2020',
  legalComments: 'none',
  write: false,
});

const code = result.outputFiles[0].text.trim();
if (code.includes('</script')) {
  throw new Error('bundle contains </script');
}

const START = '<!-- argon2id:start -->';
const END = '<!-- argon2id:end -->';
const html = readFileSync(page, 'utf8');
const from = html.indexOf(START);
const to = html.indexOf(END);
if (from < 0 || to < from) {
  throw new Error(`markers not found in ${page}`);
}

const block = `${START}
    <!-- @noble/hashes ${version} argon2idAsync (MIT, Paul Miller), generated by scripts/build-standalone-argon2.mjs -->
    <script id="argon2id">${code}</script>
    `;
writeFileSync(page, html.slice(0, from) + block + html.slice(to));
console.log(`inlined @noble/hashes ${version} argon2id (${code.length} bytes) into ${page}`);
