#!/usr/bin/env node
/**
 * Inlines @noble bundles into standalone/extract-mnemonic.html, between
 * their start and end markers, so the page decrypts BackupFile v3 and
 * derives wallets offline:
 *
 * - argon2id: @noble/hashes argon2idAsync
 * - derive: @noble/hashes pbkdf2, hmac, sha512, keccak_256 and
 *   @noble/curves secp256k1, for BIP-39, BIP-32 and addresses
 *
 * Run after upgrading @noble/hashes or @noble/curves: pnpm build:standalone
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const page = join(root, 'standalone', 'extract-mnemonic.html');

function versionOf(pkg) {
  return JSON.parse(readFileSync(join(root, 'node_modules', pkg, 'package.json'), 'utf8')).version;
}

const hashes = `@noble/hashes ${versionOf('@noble/hashes')}`;
const curves = `@noble/curves ${versionOf('@noble/curves')}`;

const bundles = [
  {
    id: 'argon2id',
    globalName: 'nobleArgon2',
    label: `${hashes} argon2idAsync`,
    contents: "export { argon2idAsync } from '@noble/hashes/argon2.js';",
  },
  {
    id: 'derive',
    globalName: 'nobleDerive',
    label: `${hashes} pbkdf2, hmac, sha512, keccak_256 and ${curves} secp256k1`,
    contents: [
      "export { pbkdf2 } from '@noble/hashes/pbkdf2.js';",
      "export { hmac } from '@noble/hashes/hmac.js';",
      "export { sha512 } from '@noble/hashes/sha2.js';",
      "export { keccak_256 } from '@noble/hashes/sha3.js';",
      "export { secp256k1 } from '@noble/curves/secp256k1.js';",
    ].join('\n'),
  },
];

let html = readFileSync(page, 'utf8');

for (const { id, globalName, label, contents } of bundles) {
  const result = await build({
    stdin: { contents, resolveDir: root, loader: 'js' },
    bundle: true,
    format: 'iife',
    globalName,
    minify: true,
    target: 'es2020',
    legalComments: 'none',
    write: false,
  });

  const code = result.outputFiles[0].text.trim();
  if (code.includes('</script')) {
    throw new Error(`${id} bundle contains </script`);
  }

  const START = `<!-- ${id}:start -->`;
  const END = `<!-- ${id}:end -->`;
  const from = html.indexOf(START);
  const to = html.indexOf(END);
  if (from < 0 || to < from) {
    throw new Error(`${id} markers not found in ${page}`);
  }

  const block = `${START}
    <!-- ${label} (MIT, Paul Miller), generated by scripts/build-standalone.mjs -->
    <script id="${id}">${code}</script>
    `;
  html = html.slice(0, from) + block + html.slice(to);
  console.log(`inlined ${label} (${code.length} bytes)`);
}

writeFileSync(page, html);
